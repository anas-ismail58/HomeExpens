export const strings: Record<Language, Record<StringKey, string>> = { ar, en };

export function translate(language: Language, key: StringKey, params?: Record<string, string | number>) {
  let text = strings[language][key];
  if (params) for (const [name, value] of Object.entries(params)) text = text.replace(`{${name}}`, String(value));
  return text;
}
